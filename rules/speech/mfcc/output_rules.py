from experta import Rule, MATCH, NOT

from facts import (
    Layer,
    ComponentGroup,
    LayerParameter,
    OptionSelection,
    TensorInfo,
    WeightShape,
    OutputStatus,
)
from utils.print_helpers import print_mfcc_result


class MFCCOutputRules:
    @Rule(
        Layer(
            layer_index=MATCH.layer_index,
            layer_name="mfcc",
            layer_title=MATCH.layer_title,
            input_shape=MATCH.input_shape,
            output_shape=MATCH.output_shape
        ),
        ComponentGroup(
            group_index=MATCH.layer_index,
            group_name="mfcc",
            internal_layers=MATCH.internal_layers,
            combine_operation=MATCH.combine_operation,
            status="computed"
        ),
        LayerParameter(
            layer_index=MATCH.layer_index,
            layer_name="mfcc",
            parameter_name="num_mfcc_coefficients",
            value=MATCH.num_mfcc_coefficients
        ),
        OptionSelection(
            layer_index=MATCH.layer_index,
            layer_name="mfcc",
            question_key="mfcc_dct_type",
            value=MATCH.dct_type,
            status="resolved"
        ),
        OptionSelection(
            layer_index=MATCH.layer_index,
            layer_name="mfcc",
            question_key="mfcc_include_c0",
            value=MATCH.include_c0,
            status="resolved"
        ),
        LayerParameter(
            layer_index=MATCH.layer_index,
            layer_name="mfcc",
            parameter_name="lifter",
            value=MATCH.lifter
        ),
        TensorInfo(
            layer_index=MATCH.layer_index,
            layer_name="mfcc",
            tensor_name="sample_rate",
            role="shape_metadata",
            shape=MATCH.sample_rate
        ),
        TensorInfo(
            layer_index=MATCH.layer_index,
            layer_name="mfcc",
            tensor_name="output_num_frames",
            role="shape_metadata",
            shape=MATCH.num_frames
        ),
        TensorInfo(
            layer_index=MATCH.layer_index,
            layer_name="mfcc",
            tensor_name="input_mel_filters",
            role="shape_metadata",
            shape=MATCH.num_mel_filters
        ),
        TensorInfo(
            layer_index=MATCH.layer_index,
            layer_name="mfcc",
            tensor_name="output_channels",
            role="shape_metadata",
            shape=MATCH.channels
        ),
        TensorInfo(
            layer_index=MATCH.layer_index,
            layer_name="mfcc",
            tensor_name="coefficient_range",
            role="shape_metadata",
            shape=MATCH.coefficient_range
        ),
        WeightShape(
            layer_index=MATCH.layer_index,
            layer_name="mfcc",
            weight_name="mfcc_parameters",
            shape=MATCH.parameter_shape
        ),
        NOT(OutputStatus(
            layer_index=MATCH.layer_index,
            output_name="layer_result_printed",
            status="printed"
        )),
        salience=50
    )
    def print_mfcc_layer_result(
        self,
        layer_index,
        layer_title,
        input_shape,
        output_shape,
        internal_layers,
        combine_operation,
        num_mfcc_coefficients,
        dct_type,
        include_c0,
        lifter,
        sample_rate,
        num_frames,
        num_mel_filters,
        channels,
        coefficient_range,
        parameter_shape
    ):
        print_mfcc_result(
            layer_index=layer_index,
            layer_title=layer_title,
            layer_name="mfcc",
            layer_kind="speech_feature_extraction_component_group",
            input_shape=input_shape,
            output_shape=output_shape,
            parameter_shape=parameter_shape,
            internal_layers=internal_layers,
            combine_operation=combine_operation,
            sample_rate=int(sample_rate),
            num_frames=int(num_frames),
            num_mel_filters=int(num_mel_filters),
            num_mfcc_coefficients=int(num_mfcc_coefficients),
            dct_type=dct_type,
            include_c0=include_c0,
            coefficient_range=coefficient_range,
            lifter=int(lifter),
            channels=int(channels)
        )

        self.declare(OutputStatus(
            layer_index=layer_index,
            output_name="layer_result_printed",
            status="printed"
        ))
