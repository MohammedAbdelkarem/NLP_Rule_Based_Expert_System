from experta import Rule, MATCH, NOT

from facts import (
    Layer,
    ComponentGroup,
    LayerParameter,
    OptionSelection,
    TensorInfo,
    WeightShape,
    OutputStatus,
)
from utils.print_helpers import print_stft_spectrum_result


class STFTSpectrumOutputRules:
    @Rule(
        Layer(
            layer_index=MATCH.layer_index,
            layer_name="stft_spectrum",
            layer_title=MATCH.layer_title,
            input_shape=MATCH.input_shape,
            output_shape=MATCH.output_shape
        ),
        ComponentGroup(
            group_index=MATCH.layer_index,
            group_name="stft_spectrum",
            internal_layers=MATCH.internal_layers,
            combine_operation=MATCH.combine_operation,
            status="computed"
        ),
        LayerParameter(
            layer_index=MATCH.layer_index,
            layer_name="stft_spectrum",
            parameter_name="n_fft",
            value=MATCH.n_fft
        ),
        OptionSelection(
            layer_index=MATCH.layer_index,
            layer_name="stft_spectrum",
            question_key="stft_output_mode",
            value=MATCH.output_mode,
            status="resolved"
        ),
        TensorInfo(
            layer_index=MATCH.layer_index,
            layer_name="stft_spectrum",
            tensor_name="sample_rate",
            role="shape_metadata",
            shape=MATCH.sample_rate
        ),
        TensorInfo(
            layer_index=MATCH.layer_index,
            layer_name="stft_spectrum",
            tensor_name="output_num_frames",
            role="shape_metadata",
            shape=MATCH.num_frames
        ),
        TensorInfo(
            layer_index=MATCH.layer_index,
            layer_name="stft_spectrum",
            tensor_name="output_frequency_bins",
            role="shape_metadata",
            shape=MATCH.frequency_bins
        ),
        TensorInfo(
            layer_index=MATCH.layer_index,
            layer_name="stft_spectrum",
            tensor_name="output_channels",
            role="shape_metadata",
            shape=MATCH.channels
        ),
        WeightShape(
            layer_index=MATCH.layer_index,
            layer_name="stft_spectrum",
            weight_name="stft_spectrum_parameters",
            shape=MATCH.parameter_shape
        ),
        NOT(OutputStatus(
            layer_index=MATCH.layer_index,
            output_name="layer_result_printed",
            status="printed"
        )),
        salience=50
    )
    def print_stft_spectrum_layer_result(
        self,
        layer_index,
        layer_title,
        input_shape,
        output_shape,
        internal_layers,
        combine_operation,
        n_fft,
        output_mode,
        sample_rate,
        num_frames,
        frequency_bins,
        channels,
        parameter_shape
    ):
        print_stft_spectrum_result(
            layer_index=layer_index,
            layer_title=layer_title,
            layer_name="stft_spectrum",
            layer_kind="speech_feature_extraction_component_group",
            input_shape=input_shape,
            output_shape=output_shape,
            parameter_shape=parameter_shape,
            internal_layers=internal_layers,
            combine_operation=combine_operation,
            sample_rate=int(sample_rate),
            n_fft=int(n_fft),
            output_mode=output_mode,
            num_frames=int(num_frames),
            frequency_bins=int(frequency_bins),
            channels=int(channels)
        )

        self.declare(OutputStatus(
            layer_index=layer_index,
            output_name="layer_result_printed",
            status="printed"
        ))
