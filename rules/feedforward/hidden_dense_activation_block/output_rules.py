from experta import MATCH, NOT, Rule

from facts import (
    ComponentGroup,
    IntermediateTensor,
    Layer,
    LayerParameter,
    OptionSelection,
    OutputStatus,
    WeightShape,
)
from utils.print_helpers import print_hidden_dense_activation_block_result


class HiddenDenseActivationBlockOutputRules:
    @Rule(
        Layer(
            layer_index=MATCH.layer_index,
            layer_name="hidden_dense_activation_block",
            layer_title=MATCH.layer_title,
            input_shape=MATCH.input_shape,
            output_shape=MATCH.output_shape,
        ),
        ComponentGroup(
            group_index=MATCH.layer_index,
            group_name="hidden_dense_activation_block",
            internal_layers=MATCH.internal_layers,
            combine_operation=MATCH.combine_operation,
            status="computed",
        ),
        OptionSelection(
            layer_index=MATCH.layer_index,
            layer_name="hidden_dense_activation_block",
            question_key="hidden_block_activation",
            value=MATCH.activation_name,
            status="resolved",
        ),
        LayerParameter(
            layer_index=MATCH.layer_index,
            layer_name="hidden_dense_activation_block",
            parameter_name="hidden_dim",
            value=MATCH.hidden_dim,
        ),
        WeightShape(
            layer_index=MATCH.layer_index,
            layer_name="hidden_dense_activation_block",
            weight_name="hidden_dense_parameters",
            shape=MATCH.parameter_shape,
        ),
        IntermediateTensor(
            layer_index=MATCH.layer_index,
            layer_name="hidden_dense_activation_block",
            tensor_name="dense_projection_output",
            shape=MATCH.projection_shape,
        ),
        IntermediateTensor(
            layer_index=MATCH.layer_index,
            layer_name="hidden_dense_activation_block",
            tensor_name="activation_output",
            shape=MATCH.activation_output_shape,
        ),
        NOT(OutputStatus(
            layer_index=MATCH.layer_index,
            output_name="layer_result_printed",
            status="printed",
        )),
        salience=50,
    )
    def print_hidden_dense_block_result(
        self,
        layer_index,
        layer_title,
        input_shape,
        output_shape,
        internal_layers,
        combine_operation,
        activation_name,
        hidden_dim,
        parameter_shape,
        projection_shape,
        activation_output_shape,
    ):
        print_hidden_dense_activation_block_result(
            layer_index=layer_index,
            layer_title=layer_title,
            layer_name="hidden_dense_activation_block",
            layer_kind="grouped_layer",
            input_shape=input_shape,
            output_shape=output_shape,
            internal_layers=internal_layers,
            combine_operation=combine_operation,
            activation_name=activation_name,
            hidden_dim=hidden_dim,
            parameter_shape=parameter_shape,
            projection_shape=projection_shape,
            activation_output_shape=activation_output_shape,
        )
        self.declare(OutputStatus(
            layer_index=layer_index,
            output_name="layer_result_printed",
            status="printed",
        ))
