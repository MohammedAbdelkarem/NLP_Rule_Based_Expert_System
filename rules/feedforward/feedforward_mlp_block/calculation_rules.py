from experta import MATCH, NOT, Rule

from facts import Layer, LayerParameter, OptionSelection, SelectedLayer, TensorInfo
from rules.feedforward.common import (
    declare_mlp_common,
    declare_rank_2_shape_metadata,
    declare_rank_3_shape_metadata,
    feature_vector_shape,
    sequence_tensor_shape,
)


class FeedforwardMLPBlockCalculationRules:
    @Rule(
        SelectedLayer(
            layer_index=MATCH.layer_index,
            previous_layer_index=0,
            layer_name="feedforward_mlp_block",
            layer_title=MATCH.layer_title,
        ),
        OptionSelection(
            layer_index=MATCH.layer_index,
            layer_name="feedforward_mlp_block",
            question_key="feedforward_input_kind",
            value="feature_vector_tensor",
            status="resolved",
        ),
        OptionSelection(
            layer_index=MATCH.layer_index,
            layer_name="feedforward_mlp_block",
            question_key="mlp_block_activation",
            value=MATCH.activation_name,
            status="resolved",
        ),
        LayerParameter(
            layer_index=MATCH.layer_index,
            layer_name="feedforward_mlp_block",
            parameter_name="batch_size",
            value=MATCH.batch_size,
        ),
        LayerParameter(
            layer_index=MATCH.layer_index,
            layer_name="feedforward_mlp_block",
            parameter_name="model_dim",
            value=MATCH.input_dim,
        ),
        LayerParameter(
            layer_index=MATCH.layer_index,
            layer_name="feedforward_mlp_block",
            parameter_name="hidden_dim",
            value=MATCH.hidden_dim,
        ),
        LayerParameter(
            layer_index=MATCH.layer_index,
            layer_name="feedforward_mlp_block",
            parameter_name="output_dim",
            value=MATCH.output_dim,
        ),
        NOT(Layer(layer_index=MATCH.layer_index)),
        salience=60,
    )
    def calculate_first_rank_2_mlp_block(
        self,
        layer_index,
        layer_title,
        activation_name,
        batch_size,
        input_dim,
        hidden_dim,
        output_dim,
    ):
        input_shape = feature_vector_shape(batch_size, input_dim)
        hidden_shape = feature_vector_shape(batch_size, hidden_dim)
        output_shape = feature_vector_shape(batch_size, output_dim)
        declare_mlp_common(
            engine=self,
            layer_index=layer_index,
            layer_title=layer_title,
            dims_count=2,
            input_shape=input_shape,
            hidden_shape=hidden_shape,
            output_shape=output_shape,
            input_dim=input_dim,
            hidden_dim=hidden_dim,
            output_dim=output_dim,
            activation_name=activation_name,
        )
        declare_rank_2_shape_metadata(
            engine=self,
            layer_index=layer_index,
            layer_name="feedforward_mlp_block",
            batch_size=batch_size,
            output_dim=output_dim,
            batch_source="mlp_input_batch_size",
            output_source="mlp_output_dimension",
        )

