from experta import MATCH, NOT, Rule

from facts import OptionSelection, ComponentGroup, LayerParameter, SelectedLayer, TensorInfo
from rules.classification_heads.common import (
    declare_binary_logistic_head_rank_2,
    declare_binary_logistic_head_rank_3,
    make_rank_2_shape,
    make_rank_3_shape,
)


class BinaryLogisticRegressionHeadCalculationRules:
    @Rule(
        SelectedLayer(
            layer_index=MATCH.layer_index,
            previous_layer_index=0,
            layer_name="binary_logistic_regression_head",
            layer_title=MATCH.layer_title,
        ),
        LayerParameter(
            layer_index=MATCH.layer_index,
            layer_name="binary_logistic_regression_head",
            parameter_name="batch_size",
            value=MATCH.batch_size,
        ),
        OptionSelection(
            layer_index=MATCH.layer_index,
            layer_name="binary_logistic_regression_head",
            question_key="classifier_input_rank",
            value="rank_2",
            status="resolved",
        ),
        LayerParameter(
            layer_index=MATCH.layer_index,
            layer_name="binary_logistic_regression_head",
            parameter_name="input_dim",
            value=MATCH.input_dim,
        ),
        NOT(
            LayerParameter(
                layer_index=MATCH.layer_index,
                layer_name="binary_logistic_regression_head",
                parameter_name="sequence_length",
            ),
        ),
        NOT(ComponentGroup(group_index=MATCH.layer_index)),
        salience=60,
    )
    def calculate_first_rank_2_binary_head(
        self,
        layer_index,
        layer_title,
        batch_size,
        input_dim
    ):
        input_shape = make_rank_2_shape(batch_size, input_dim)
        output_shape = make_rank_2_shape(batch_size, 1)
        declare_binary_logistic_head_rank_2(
            engine=self,
            layer_index=layer_index,
            layer_title=layer_title,
            input_shape=input_shape,
            output_shape=output_shape,
            input_dim=input_dim,
            batch_size=batch_size,
        )

    @Rule(
        SelectedLayer(
            layer_index=MATCH.layer_index,
            previous_layer_index=0,
            layer_name="binary_logistic_regression_head",
            layer_title=MATCH.layer_title,
        ),
        LayerParameter(
            layer_index=MATCH.layer_index,
            layer_name="binary_logistic_regression_head",
            parameter_name="batch_size",
            value=MATCH.batch_size,
        ),
        OptionSelection(
            layer_index=MATCH.layer_index,
            layer_name="binary_logistic_regression_head",
            question_key="classifier_input_rank",
            value="rank_3",
            status="resolved",
        ),
        LayerParameter(
            layer_index=MATCH.layer_index,
            layer_name="binary_logistic_regression_head",
            parameter_name="sequence_length",
            value=MATCH.sequence_length,
        ),
        LayerParameter(
            layer_index=MATCH.layer_index,
            layer_name="binary_logistic_regression_head",
            parameter_name="input_dim",
            value=MATCH.input_dim,
        ),
        NOT(ComponentGroup(group_index=MATCH.layer_index)),
        salience=60,
    )
    def calculate_first_rank_3_binary_head(
        self,
        layer_index,
        layer_title,
        batch_size,
        sequence_length,
        input_dim
    ):
        input_shape = make_rank_3_shape(batch_size, input_dim, sequence_length)
        output_shape = make_rank_3_shape(batch_size, 1, sequence_length)
        declare_binary_logistic_head_rank_3(
            engine=self,
            layer_index=layer_index,
            layer_title=layer_title,
            input_shape=input_shape,
            output_shape=output_shape,
            input_dim=input_dim,
            batch_size=batch_size,
            sequence_length=sequence_length,
        )

    @Rule(
        SelectedLayer(
            layer_index=MATCH.layer_index,
            previous_layer_index=MATCH.previous_layer_index,
            layer_name="binary_logistic_regression_head",
            layer_title=MATCH.layer_title,
        ),
        TensorInfo(
            layer_index=MATCH.previous_layer_index,
            role="output",
            dims_count=2,
            shape=MATCH.input_shape,
            data_type="float_hidden_tensor",
        ),
        TensorInfo(
            layer_index=MATCH.previous_layer_index,
            tensor_name="output_batch_size",
            role="shape_metadata",
            shape=MATCH.batch_size,
        ),
        TensorInfo(
            layer_index=MATCH.previous_layer_index,
            tensor_name="output_model_dim",
            role="shape_metadata",
            shape=MATCH.input_dim,
        ),
        NOT(ComponentGroup(group_index=MATCH.layer_index)),
        salience=60,
    )
    def calculate_rank_2_binary_head_after_previous(
        self,
        layer_index,
        layer_title,
        input_shape,
        batch_size,
        input_dim
    ):
        output_shape = make_rank_2_shape(batch_size, 1)
        declare_binary_logistic_head_rank_2(
            engine=self,
            layer_index=layer_index,
            layer_title=layer_title,
            input_shape=input_shape,
            output_shape=output_shape,
            input_dim=input_dim,
            batch_size=batch_size,
            batch_source="previous_layer_output_batch_size",
            output_dim_source="binary_output_dimension",
        )

    @Rule(
        SelectedLayer(
            layer_index=MATCH.layer_index,
            previous_layer_index=MATCH.previous_layer_index,
            layer_name="binary_logistic_regression_head",
            layer_title=MATCH.layer_title,
        ),
        TensorInfo(
            layer_index=MATCH.previous_layer_index,
            role="output",
            dims_count=3,
            shape=MATCH.input_shape,
            data_type="float_hidden_tensor",
        ),
        TensorInfo(
            layer_index=MATCH.previous_layer_index,
            tensor_name="output_batch_size",
            role="shape_metadata",
            shape=MATCH.batch_size,
        ),
        TensorInfo(
            layer_index=MATCH.previous_layer_index,
            tensor_name="output_sequence_length",
            role="shape_metadata",
            shape=MATCH.sequence_length,
        ),
        TensorInfo(
            layer_index=MATCH.previous_layer_index,
            tensor_name="output_model_dim",
            role="shape_metadata",
            shape=MATCH.input_dim,
        ),
        NOT(ComponentGroup(group_index=MATCH.layer_index)),
        salience=60,
    )
    def calculate_rank_3_binary_head_after_previous(
        self,
        layer_index,
        layer_title,
        input_shape,
        batch_size,
        sequence_length,
        input_dim
    ):
        output_shape = make_rank_3_shape(batch_size, 1, sequence_length)
        declare_binary_logistic_head_rank_3(
            engine=self,
            layer_index=layer_index,
            layer_title=layer_title,
            input_shape=input_shape,
            output_shape=output_shape,
            input_dim=input_dim,
            batch_size=batch_size,
            sequence_length=sequence_length,
            batch_source="previous_layer_output_batch_size",
            sequence_source="previous_layer_output_sequence_length",
            output_dim_source="binary_output_dimension",
        )
