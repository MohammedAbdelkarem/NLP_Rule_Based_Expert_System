from experta import MATCH, NOT, Rule

from facts import Layer, LayerParameter, OptionSelection, SelectedLayer, TensorInfo
from rules.classification_heads.common import (
    classifier_shape,
    declare_classifier_common,
)


class FeedforwardClassifierHeadCalculationRules:
    @Rule(
        SelectedLayer(
            layer_index=MATCH.layer_index,
            previous_layer_index=0,
            layer_name="feedforward_classifier_head",
            layer_title=MATCH.layer_title,
        ),
        OptionSelection(
            layer_index=MATCH.layer_index,
            layer_name="feedforward_classifier_head",
            question_key="classifier_input_kind",
            value="feature_vector_tensor",
            status="resolved",
        ),
        OptionSelection(
            layer_index=MATCH.layer_index,
            layer_name="feedforward_classifier_head",
            question_key="classifier_mode",
            value="binary_classification",
            status="resolved",
        ),
        LayerParameter(
            layer_index=MATCH.layer_index,
            layer_name="feedforward_classifier_head",
            parameter_name="batch_size",
            value=MATCH.batch_size,
        ),
        LayerParameter(
            layer_index=MATCH.layer_index,
            layer_name="feedforward_classifier_head",
            parameter_name="model_dim",
            value=MATCH.input_dim,
        ),
        LayerParameter(
            layer_index=MATCH.layer_index,
            layer_name="feedforward_classifier_head",
            parameter_name="hidden_dim",
            value=MATCH.hidden_dim,
        ),
        LayerParameter(
            layer_index=MATCH.layer_index,
            layer_name="feedforward_classifier_head",
            parameter_name="num_classes",
            value=1,
        ),
        NOT(Layer(layer_index=MATCH.layer_index)),
        salience=60,
    )
    def calculate_first_binary_classifier_head(
        self,
        layer_index,
        layer_title,
        batch_size,
        input_dim,
        hidden_dim,
    ):
        input_shape = classifier_shape(batch_size, input_dim)
        hidden_shape = classifier_shape(batch_size, hidden_dim)
        logits_shape = classifier_shape(batch_size, 1)
        declare_classifier_common(
            engine=self,
            layer_index=layer_index,
            layer_title=layer_title,
            input_shape=input_shape,
            hidden_shape=hidden_shape,
            logits_shape=logits_shape,
            probability_shape=logits_shape,
            input_dim=input_dim,
            hidden_dim=hidden_dim,
            output_dim=1,
            batch_size=batch_size,
            classifier_mode="binary_classification",
            probability_activation="sigmoid",
        )

