from facts import (
    CalculationStep,
    Layer,
    LayerMetadata,
    TensorInfo,
    TransformerStage,
    WeightShape,
)


def declare_activation_rank_2_metadata(
    engine,
    layer_index,
    layer_name,
    batch_size,
    model_dim,
    batch_source,
    model_dim_source,
):
    engine.declare(TensorInfo(
        layer_index=layer_index,
        layer_name=layer_name,
        tensor_name="output_batch_size",
        role="shape_metadata",
        dims_count=1,
        shape=str(batch_size),
        data_type="integer_dimension_value",
        source=batch_source,
    ))
    engine.declare(TensorInfo(
        layer_index=layer_index,
        layer_name=layer_name,
        tensor_name="output_model_dim",
        role="shape_metadata",
        dims_count=1,
        shape=str(model_dim),
        data_type="integer_dimension_value",
        source=model_dim_source,
    ))


