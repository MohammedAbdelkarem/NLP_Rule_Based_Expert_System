from experta import MATCH, NOT, Rule

from facts import (
    OptionSelection,
    CalculationStep,
    Layer,
    LayerMetadata,
    LayerParameter,
    SelectedLayer,
    TensorInfo,
    WeightShape,
)
from rules.classification_heads.common import (
    declare_output_shape_metadata_rank_2,
    declare_output_shape_metadata_rank_3,
    make_rank_2_shape,
    make_rank_3_shape,
)


class SigmoidCalculationRules:
    @Rule(
        SelectedLayer(
            layer_index=MATCH.layer_index,
            previous_layer_index=0,
            layer_name="sigmoid",
            layer_title=MATCH.layer_title,
        ),
        LayerParameter(
            layer_index=MATCH.layer_index,
            layer_name="sigmoid",
            parameter_name="batch_size",
            value=MATCH.batch_size,
        ),
        OptionSelection(
            layer_index=MATCH.layer_index,
            layer_name="sigmoid",
            question_key="sigmoid_input_rank",
            value="rank_2",
            status="resolved",
        ),
        NOT(
            LayerParameter(
                layer_index=MATCH.layer_index,
                layer_name="sigmoid",
                parameter_name="sequence_length",
            ),
        ),
        NOT(Layer(layer_index=MATCH.layer_index)),
        salience=60,
    )
    def calculate_first_rank_2_sigmoid(self, layer_index, layer_title, batch_size):
        self._declare_sigmoid_rank_2(
            layer_index=layer_index,
            layer_title=layer_title,
            input_shape=make_rank_2_shape(batch_size, 1),
            batch_size=batch_size,
            substitution=f"binary logits shape ({batch_size}, 1)",
        )

    @Rule(
        SelectedLayer(
            layer_index=MATCH.layer_index,
            previous_layer_index=0,
            layer_name="sigmoid",
            layer_title=MATCH.layer_title,
        ),
        LayerParameter(
            layer_index=MATCH.layer_index,
            layer_name="sigmoid",
            parameter_name="batch_size",
            value=MATCH.batch_size,
        ),
        OptionSelection(
            layer_index=MATCH.layer_index,
            layer_name="sigmoid",
            question_key="sigmoid_input_rank",
            value="rank_3",
            status="resolved",
        ),
        LayerParameter(
            layer_index=MATCH.layer_index,
            layer_name="sigmoid",
            parameter_name="sequence_length",
            value=MATCH.sequence_length,
        ),
        NOT(Layer(layer_index=MATCH.layer_index)),
        salience=60,
    )
    def calculate_first_rank_3_sigmoid(
        self,
        layer_index,
        layer_title,
        batch_size,
        sequence_length
    ):
        self._declare_sigmoid_rank_3(
            layer_index=layer_index,
            layer_title=layer_title,
            input_shape=make_rank_3_shape(batch_size, 1, sequence_length),
            batch_size=batch_size,
            sequence_length=sequence_length,
            substitution=f"binary logits shape ({batch_size}, {sequence_length}, 1)",
        )

    @Rule(
        SelectedLayer(
            layer_index=MATCH.layer_index,
            previous_layer_index=MATCH.previous_layer_index,
            layer_name="sigmoid",
            layer_title=MATCH.layer_title,
        ),
        TensorInfo(
            layer_index=MATCH.previous_layer_index,
            role="output",
            dims_count=2,
            shape=MATCH.previous_shape,
            data_type="binary_logits",
        ),
        TensorInfo(
            layer_index=MATCH.previous_layer_index,
            tensor_name="output_batch_size",
            role="shape_metadata",
            shape=MATCH.batch_size,
        ),
        TensorInfo(
            layer_index=MATCH.previous_layer_index,
            tensor_name="output_model_dim",
            role="shape_metadata",
            shape="1",
        ),
        NOT(Layer(layer_index=MATCH.layer_index)),
        salience=60,
    )
    def calculate_rank_2_sigmoid_after_previous(
        self,
        layer_index,
        layer_title,
        previous_shape,
        batch_size
    ):
        self._declare_sigmoid_rank_2(
            layer_index=layer_index,
            layer_title=layer_title,
            input_shape=previous_shape,
            batch_size=batch_size,
            substitution=f"previous binary logits shape {previous_shape}",
        )

    @Rule(
        SelectedLayer(
            layer_index=MATCH.layer_index,
            previous_layer_index=MATCH.previous_layer_index,
            layer_name="sigmoid",
            layer_title=MATCH.layer_title,
        ),
        TensorInfo(
            layer_index=MATCH.previous_layer_index,
            role="output",
            dims_count=3,
            shape=MATCH.previous_shape,
            data_type="binary_logits",
        ),
        TensorInfo(
            layer_index=MATCH.previous_layer_index,
            tensor_name="output_batch_size",
            role="shape_metadata",
            shape=MATCH.batch_size,
        ),
        TensorInfo(
            layer_index=MATCH.previous_layer_index,
            tensor_name="output_sequence_length",
            role="shape_metadata",
            shape=MATCH.sequence_length,
        ),
        TensorInfo(
            layer_index=MATCH.previous_layer_index,
            tensor_name="output_model_dim",
            role="shape_metadata",
            shape="1",
        ),
        NOT(Layer(layer_index=MATCH.layer_index)),
        salience=60,
    )
    def calculate_rank_3_sigmoid_after_previous(
        self,
        layer_index,
        layer_title,
        previous_shape,
        batch_size,
        sequence_length
    ):
        self._declare_sigmoid_rank_3(
            layer_index=layer_index,
            layer_title=layer_title,
            input_shape=previous_shape,
            batch_size=batch_size,
            sequence_length=sequence_length,
            substitution=f"previous binary logits shape {previous_shape}",
        )

    def _declare_sigmoid_common(
        self,
        layer_index,
        layer_title,
        input_shape,
        output_shape,
        dims_count,
        substitution
    ):
        self.declare(
            WeightShape(
                layer_index=layer_index,
                layer_name="sigmoid",
                weight_name="sigmoid_parameters",
                shape="no trainable parameters",
            ),
        )
        self.declare(
            TensorInfo(
                layer_index=layer_index,
                layer_name="sigmoid",
                tensor_name="sigmoid_output",
                role="output",
                dims_count=dims_count,
                shape=output_shape,
                data_type="binary_probability",
                source="sigmoid_probability_activation",
            ),
        )
        self.declare(
            LayerMetadata(
                layer_index=layer_index,
                layer_name="sigmoid",
                layer_kind="simple_layer",
                layer_role="activation",
                repeat_policy="repeat_allowed",
                consecutive_repeat_policy="no_consecutive_activation",
                terminal_status="non_terminal",
            ),
        )
        self.declare(
            CalculationStep(
                layer_index=layer_index,
                layer_name="sigmoid",
                step_key=f"layer_{layer_index}_sigmoid_activation",
                previous_step_key="none",
                step_order=1,
                title="Sigmoid probability activation",
                formula="sigmoid(z) = 1 / (1 + exp(-z))",
                substitution=substitution,
                result=output_shape,
            ),
        )
        self.declare(
            Layer(
                layer_index=layer_index,
                layer_name="sigmoid",
                layer_title=layer_title,
                input_shape=input_shape,
                output_shape=output_shape,
            ),
        )

    def _declare_sigmoid_rank_2(
        self,
        layer_index,
        layer_title,
        input_shape,
        batch_size,
        substitution
    ):
        declare_output_shape_metadata_rank_2(
            engine=self,
            layer_index=layer_index,
            layer_name="sigmoid",
            batch_size=batch_size,
            output_dim=1,
            batch_source="sigmoid_input_batch_size",
            output_dim_source="sigmoid_binary_output_dimension",
        )
        self._declare_sigmoid_common(
            layer_index=layer_index,
            layer_title=layer_title,
            input_shape=input_shape,
            output_shape=input_shape,
            dims_count=2,
            substitution=substitution,
        )

    def _declare_sigmoid_rank_3(
        self,
        layer_index,
        layer_title,
        input_shape,
        batch_size,
        sequence_length,
        substitution
    ):
        declare_output_shape_metadata_rank_3(
            engine=self,
            layer_index=layer_index,
            layer_name="sigmoid",
            batch_size=batch_size,
            output_dim=1,
            sequence_length=sequence_length,
            batch_source="sigmoid_input_batch_size",
            output_dim_source="sigmoid_binary_output_dimension",
            sequence_source="sigmoid_input_sequence_length",
        )
        self._declare_sigmoid_common(
            layer_index=layer_index,
            layer_title=layer_title,
            input_shape=input_shape,
            output_shape=input_shape,
            dims_count=3,
            substitution=substitution,
        )
