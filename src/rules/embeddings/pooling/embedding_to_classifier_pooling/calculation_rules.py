from experta import MATCH, NOT, Rule

from src.facts import (
    CalculationStep,
    Layer,
    LayerMetadata,
    LayerParameter,
    OptionSelection,
    SelectedLayer,
    TensorInfo,
    TransformerStage,
    WeightShape,
)


class EmbeddingToClassifierPoolingCalculationRules:
    @Rule(
        SelectedLayer(
            layer_index=MATCH.layer_index,
            previous_layer_index=0,
            layer_name="embedding_to_classifier_pooling",
            layer_title=MATCH.layer_title,
        ),
        OptionSelection(
            layer_index=MATCH.layer_index,
            layer_name="embedding_to_classifier_pooling",
            question_key="pooling_input_kind",
            value="sequence_embedding_tensor",
            status="resolved",
        ),
        LayerParameter(
            layer_index=MATCH.layer_index,
            layer_name="embedding_to_classifier_pooling",
            parameter_name="batch_size",
            value=MATCH.batch_size,
        ),
        LayerParameter(
            layer_index=MATCH.layer_index,
            layer_name="embedding_to_classifier_pooling",
            parameter_name="sequence_length",
            value=MATCH.sequence_length,
        ),
        LayerParameter(
            layer_index=MATCH.layer_index,
            layer_name="embedding_to_classifier_pooling",
            parameter_name="model_dim",
            value=MATCH.model_dim,
        ),
        NOT(Layer(layer_index=MATCH.layer_index)),
        salience=60,
    )
    def calculate_first_pooling_adapter(
        self,
        layer_index,
        layer_title,
        batch_size,
        sequence_length,
        model_dim,
    ):
        input_shape = f"({batch_size}, {sequence_length}, {model_dim})"
        output_shape = f"({batch_size}, {model_dim})"
        self._declare_pooling_adapter(
            layer_index=layer_index,
            layer_title=layer_title,
            input_shape=input_shape,
            output_shape=output_shape,
            batch_size=batch_size,
            model_dim=model_dim,
            batch_source="pooling_input_batch_size",
            model_dim_source="pooling_embedding_dimension",
            substitution=f"mean over {sequence_length} token vectors",
        )

    @Rule(
        SelectedLayer(
            layer_index=MATCH.layer_index,
            previous_layer_index=MATCH.previous_layer_index,
            layer_name="embedding_to_classifier_pooling",
            layer_title=MATCH.layer_title,
        ),
        TensorInfo(
            layer_index=MATCH.previous_layer_index,
            role="output",
            dims_count=3,
            shape=MATCH.previous_output_shape,
            data_type="float_hidden_tensor",
        ),
        TensorInfo(
            layer_index=MATCH.previous_layer_index,
            tensor_name="output_batch_size",
            role="shape_metadata",
            shape=MATCH.batch_size,
        ),
        TensorInfo(
            layer_index=MATCH.previous_layer_index,
            tensor_name="output_sequence_length",
            role="shape_metadata",
            shape=MATCH.sequence_length,
        ),
        TensorInfo(
            layer_index=MATCH.previous_layer_index,
            tensor_name="output_model_dim",
            role="shape_metadata",
            shape=MATCH.model_dim,
        ),
        NOT(Layer(layer_index=MATCH.layer_index)),
        salience=60,
    )
    def calculate_pooling_after_previous(
        self,
        layer_index,
        previous_layer_index,
        layer_title,
        previous_output_shape,
        batch_size,
        sequence_length,
        model_dim,
    ):
        output_shape = f"({batch_size}, {model_dim})"
        self._declare_pooling_adapter(
            layer_index=layer_index,
            layer_title=layer_title,
            input_shape=previous_output_shape,
            output_shape=output_shape,
            batch_size=batch_size,
            model_dim=model_dim,
            batch_source=f"layer_{previous_layer_index}_output_batch_size",
            model_dim_source=f"layer_{previous_layer_index}_output_model_dim",
            substitution=f"mean over {sequence_length} token vectors",
        )

    def _declare_pooling_adapter(
        self,
        layer_index,
        layer_title,
        input_shape,
        output_shape,
        batch_size,
        model_dim,
        batch_source,
        model_dim_source,
        substitution,
    ):
        self.declare(WeightShape(
            layer_index=layer_index,
            layer_name="embedding_to_classifier_pooling",
            weight_name="pooling_parameters",
            shape="no trainable parameters",
        ))
        self.declare(TensorInfo(
            layer_index=layer_index,
            layer_name="embedding_to_classifier_pooling",
            tensor_name="pooled_classifier_feature_vector",
            role="output",
            dims_count=2,
            shape=output_shape,
            data_type="float_hidden_tensor",
            source="mean_pooling_over_sequence_axis",
        ))
        self.declare(TensorInfo(
            layer_index=layer_index,
            layer_name="embedding_to_classifier_pooling",
            tensor_name="output_batch_size",
            role="shape_metadata",
            dims_count=1,
            shape=str(batch_size),
            data_type="integer_dimension_value",
            source=batch_source,
        ))
        self.declare(TensorInfo(
            layer_index=layer_index,
            layer_name="embedding_to_classifier_pooling",
            tensor_name="output_model_dim",
            role="shape_metadata",
            dims_count=1,
            shape=str(model_dim),
            data_type="integer_dimension_value",
            source=model_dim_source,
        ))
        self.declare(LayerMetadata(
            layer_index=layer_index,
            layer_name="embedding_to_classifier_pooling",
            layer_kind="adapter_layer",
            layer_role="sequence_to_feature_vector_adapter",
            repeat_policy="repeat_allowed",
            consecutive_repeat_policy="no_consecutive_pooling",
            terminal_status="non_terminal",
        ))
        self.declare(TransformerStage(
            layer_index=layer_index,
            layer_name="embedding_to_classifier_pooling",
            stage_name="embedding_to_classifier_pooling_completed",
            status="computed",
        ))
        self.declare(CalculationStep(
            layer_index=layer_index,
            layer_name="embedding_to_classifier_pooling",
            step_key=f"layer_{layer_index}_mean_pooling_shape",
            previous_step_key="none",
            step_order=1,
            title="Mean pooling adapter shape",
            formula="Y = mean(X, axis=sequence_length)",
            substitution=substitution,
            result=output_shape,
        ))
        self.declare(Layer(
            layer_index=layer_index,
            layer_name="embedding_to_classifier_pooling",
            layer_title=layer_title,
            input_shape=input_shape,
            output_shape=output_shape,
        ))
