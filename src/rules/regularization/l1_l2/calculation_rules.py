class L1L2RegularizationCalculationRules:
    @Rule(
        SelectedLayer(
            layer_index=MATCH.layer_index,
            previous_layer_index=MATCH.previous_layer_index,
            layer_name="l1_l2_regularization",
            layer_title=MATCH.layer_title,
        ),
        TensorInfo(
            layer_index=MATCH.previous_layer_index,
            role="output",
            dims_count=2,
            shape=MATCH.previous_shape,
            data_type=MATCH.previous_data_type,
        ),
        TensorInfo(
            layer_index=MATCH.previous_layer_index,
            tensor_name="output_batch_size",
            role="shape_metadata",
            shape=MATCH.batch_size,
        ),
        TensorInfo(
            layer_index=MATCH.previous_layer_index,
            tensor_name="output_model_dim",
            role="shape_metadata",
            shape=MATCH.output_dim,
        ),
        WeightShape(layer_index=MATCH.previous_layer_index, shape=MATCH.previous_weights),
        OptionSelection(
            layer_index=MATCH.layer_index,
            layer_name="l1_l2_regularization",
            question_key="regularization_type",
            value="l1",
            status="resolved",
        ),
        LayerParameter(
            layer_index=MATCH.layer_index,
            layer_name="l1_l2_regularization",
            parameter_name="lambda_exponent",
            value=MATCH.lambda_exponent,
        ),
        NOT(TrainingComponent(component_index=MATCH.layer_index)),
        salience=60,
    )
    def calculate_rank_2_l1_regularization(
        self,
        layer_index,
        layer_title,
        previous_layer_index,
        previous_shape,
        previous_data_type,
        batch_size,
        output_dim,
        previous_weights,
        lambda_exponent
    ):
        self._declare_regularization_rank_2(
            layer_index=layer_index,
            layer_title=layer_title,
            previous_layer_index=previous_layer_index,
            previous_shape=previous_shape,
            previous_data_type=previous_data_type,
            previous_weights=previous_weights,
            regularization_type="l1",
            regularization_title="L1 Regularization",
            penalty_formula="λ × ||W||₁",
            lambda_exponent=lambda_exponent,
            batch_size=batch_size,
            output_dim=output_dim,
        )

