    def _declare_regularization_common(
        self,
        layer_index,
        layer_title,
        previous_layer_index,
        dims_count,
        previous_shape,
        previous_data_type,
        previous_weights,
        regularization_type,
        regularization_title,
        penalty_formula,
        lambda_exponent,
        batch_size,
        output_dim
    ):
        lambda_value = f"1e-{lambda_exponent}"
        self.declare(TrainingComponent(
            component_index=layer_index,
            component_name="l1_l2_regularization",
            component_title=layer_title,
            component_type="training_constraint",
            input_shape=(
                f"previous trainable parameters from layer {previous_layer_index}; "
                f"preserved forward output {previous_shape}"
            ),
            output_shape=previous_shape,
            status="computed",
            used_during="training_only",
        ))
        self.declare(WeightShape(
            layer_index=layer_index,
            layer_name="l1_l2_regularization",
            weight_name="regularization_parameters",
            shape=f"no trainable parameters; type={regularization_type}; lambda={lambda_value}",
        ))
        self.declare(TensorInfo(
            layer_index=layer_index,
            layer_name="l1_l2_regularization",
            tensor_name="regularization_preserved_forward_output",
            role="output",
            dims_count=dims_count,
            shape=previous_shape,
            data_type=previous_data_type,
            source="regularization_preserves_forward_prediction_tensor",
        ))
        self.declare(TensorInfo(
            layer_index=layer_index,
            layer_name="l1_l2_regularization",
            tensor_name="output_batch_size",
            role="shape_metadata",
            dims_count=1,
            shape=str(batch_size),
            data_type="integer_dimension_value",
            source=f"copied_from_layer_{previous_layer_index}",
        ))
        self.declare(TensorInfo(
            layer_index=layer_index,
            layer_name="l1_l2_regularization",
            tensor_name="output_model_dim",
            role="shape_metadata",
            dims_count=1,
            shape=str(output_dim),
            data_type="integer_dimension_value",
            source=f"copied_from_layer_{previous_layer_index}",
        ))
        self.declare(LayerMetadata(
            layer_index=layer_index,
            layer_name="l1_l2_regularization",
            layer_kind="training_component",
            layer_role="regularization_constraint",
            repeat_policy="repeat_allowed",
            consecutive_repeat_policy="no_consecutive_regularization",
            terminal_status="non_terminal",
        ))
        self.declare(CalculationStep(
            layer_index=layer_index,
            layer_name="l1_l2_regularization",
            step_key=f"layer_{layer_index}_regularization_penalty",
            previous_step_key="none",
            step_order=1,
            title=regularization_title,
            formula=f"total_loss = task_loss + {penalty_formula}",
            substitution=f"lambda={lambda_value}; applies to previous weights: {previous_weights}",
            result=(
                f"training penalty available; forward output shape preserved as "
                f"{previous_shape}"
            ),
        ))

