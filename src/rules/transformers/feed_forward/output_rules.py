from experta import Rule, MATCH, NOT

from src.facts import (
    Layer,
    ComponentGroup,
    OptionSelection,
    LayerParameter,
    IntermediateTensor,
    WeightShape,
    OutputStatus
)
from src.utils.print_helpers import print_feed_forward_result


class FeedForwardOutputRules:
    @Rule(
        Layer(
            layer_index=MATCH.layer_index,
            layer_name="feed_forward",
            layer_title=MATCH.layer_title,
            input_shape=MATCH.input_shape,
            output_shape=MATCH.output_shape
        ),
        ComponentGroup(
            group_index=MATCH.layer_index,
            group_name="feed_forward",
            internal_layers=MATCH.internal_layers,
            combine_operation=MATCH.combine_operation,
            status="computed"
        ),
        OptionSelection(
            layer_index=MATCH.layer_index,
            layer_name="feed_forward",
            question_key="ffn_activation",
            value=MATCH.activation_name,
            status="resolved"
        ),
        LayerParameter(
            layer_index=MATCH.layer_index,
            layer_name="feed_forward",
            parameter_name="feed_forward_dim",
            value=MATCH.feed_forward_dim
        ),
        WeightShape(
            layer_index=MATCH.layer_index,
            layer_name="feed_forward",
            weight_name="feed_forward_parameters",
            shape=MATCH.parameter_shape
        ),
        IntermediateTensor(
            layer_index=MATCH.layer_index,
            layer_name="feed_forward",
            tensor_name="first_projection_output",
            shape=MATCH.first_projection_shape
        ),
        IntermediateTensor(
            layer_index=MATCH.layer_index,
            layer_name="feed_forward",
            tensor_name="activation_output",
            shape=MATCH.activation_output_shape
        ),
        IntermediateTensor(
            layer_index=MATCH.layer_index,
            layer_name="feed_forward",
            tensor_name="second_projection_output",
            shape=MATCH.second_projection_shape
        ),
        NOT(OutputStatus(
            layer_index=MATCH.layer_index,
            output_name="layer_result_printed",
            status="printed"
        )),
        salience=50
    )
    def print_feed_forward_layer_result(
        self,
        layer_index,
        layer_title,
        input_shape,
        output_shape,
        internal_layers,
        combine_operation,
        activation_name,
        feed_forward_dim,
        parameter_shape,
        first_projection_shape,
        activation_output_shape,
        second_projection_shape
    ):
        print_feed_forward_result(
            layer_index=layer_index,
            layer_title=layer_title,
            layer_name="feed_forward",
            layer_kind="grouped_layer",
            input_shape=input_shape,
            output_shape=output_shape,
            internal_layers=internal_layers,
            combine_operation=combine_operation,
            activation_name=activation_name,
            feed_forward_dim=feed_forward_dim,
            parameter_shape=parameter_shape,
            first_projection_shape=first_projection_shape,
            activation_output_shape=activation_output_shape,
            second_projection_shape=second_projection_shape
        )

        self.declare(OutputStatus(
            layer_index=layer_index,
            output_name="layer_result_printed",
            status="printed"
        ))
