from experta import Rule, MATCH, NOT

from src.facts import (
    Layer,
    ComponentGroup,
    LayerParameter,
    IntermediateTensor,
    WeightShape,
    OutputStatus
)
from src.utils.print_helpers import print_multi_head_attention_result


class MultiHeadAttentionOutputRules:
    @Rule(
        Layer(
            layer_index=MATCH.layer_index,
            layer_name="multi_head_attention",
            layer_title=MATCH.layer_title,
            input_shape=MATCH.input_shape,
            output_shape=MATCH.output_shape
        ),
        ComponentGroup(
            group_index=MATCH.layer_index,
            group_name="multi_head_attention",
            internal_layers=MATCH.internal_layers,
            combine_operation=MATCH.combine_operation,
            status="computed"
        ),
        LayerParameter(
            layer_index=MATCH.layer_index,
            layer_name="multi_head_attention",
            parameter_name="num_heads",
            value=MATCH.num_heads
        ),
        LayerParameter(
            layer_index=MATCH.layer_index,
            layer_name="multi_head_attention",
            parameter_name="head_dim",
            value=MATCH.head_dim
        ),
        WeightShape(
            layer_index=MATCH.layer_index,
            layer_name="multi_head_attention",
            weight_name="multi_head_attention_parameters",
            shape=MATCH.parameter_shape
        ),
        IntermediateTensor(
            layer_index=MATCH.layer_index,
            layer_name="multi_head_attention",
            tensor_name="query_tensor",
            shape=MATCH.query_shape
        ),
        IntermediateTensor(
            layer_index=MATCH.layer_index,
            layer_name="multi_head_attention",
            tensor_name="key_tensor",
            shape=MATCH.key_shape
        ),
        IntermediateTensor(
            layer_index=MATCH.layer_index,
            layer_name="multi_head_attention",
            tensor_name="value_tensor",
            shape=MATCH.value_shape
        ),
        IntermediateTensor(
            layer_index=MATCH.layer_index,
            layer_name="multi_head_attention",
            tensor_name="attention_scores",
            shape=MATCH.attention_scores_shape
        ),
        IntermediateTensor(
            layer_index=MATCH.layer_index,
            layer_name="multi_head_attention",
            tensor_name="attention_weights",
            shape=MATCH.attention_weights_shape
        ),
        IntermediateTensor(
            layer_index=MATCH.layer_index,
            layer_name="multi_head_attention",
            tensor_name="head_output",
            shape=MATCH.head_output_shape
        ),
        IntermediateTensor(
            layer_index=MATCH.layer_index,
            layer_name="multi_head_attention",
            tensor_name="concatenated_heads",
            shape=MATCH.concatenated_heads_shape
        ),
        NOT(OutputStatus(
            layer_index=MATCH.layer_index,
            output_name="layer_result_printed",
            status="printed"
        )),
        salience=50
    )
    def print_multi_head_attention_layer_result(
        self,
        layer_index,
        layer_title,
        input_shape,
        output_shape,
        internal_layers,
        combine_operation,
        num_heads,
        head_dim,
        parameter_shape,
        query_shape,
        key_shape,
        value_shape,
        attention_scores_shape,
        attention_weights_shape,
        head_output_shape,
        concatenated_heads_shape
    ):
        print_multi_head_attention_result(
            layer_index=layer_index,
            layer_title=layer_title,
            layer_name="multi_head_attention",
            layer_kind="grouped_layer",
            input_shape=input_shape,
            output_shape=output_shape,
            internal_layers=internal_layers,
            combine_operation=combine_operation,
            num_heads=num_heads,
            head_dim=head_dim,
            parameter_shape=parameter_shape,
            query_shape=query_shape,
            key_shape=key_shape,
            value_shape=value_shape,
            attention_scores_shape=attention_scores_shape,
            attention_weights_shape=attention_weights_shape,
            head_output_shape=head_output_shape,
            concatenated_heads_shape=concatenated_heads_shape
        )

        self.declare(OutputStatus(
            layer_index=layer_index,
            output_name="layer_result_printed",
            status="printed"
        ))
