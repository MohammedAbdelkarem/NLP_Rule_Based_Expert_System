from experta import Rule, MATCH, NOT

from src.facts import (
    Layer,
    LayerParameter,
    OptionSelection,
    TensorInfo,
    WeightShape,
    OutputStatus,
)
from src.utils.print_helpers import print_log_mel_spectrogram_result


class LogMelSpectrogramOutputRules:
    @Rule(
        Layer(
            layer_index=MATCH.layer_index,
            layer_name="log_mel_spectrogram",
            layer_title=MATCH.layer_title,
            input_shape=MATCH.input_shape,
            output_shape=MATCH.output_shape
        ),
        LayerParameter(
            layer_index=MATCH.layer_index,
            layer_name="log_mel_spectrogram",
            parameter_name="epsilon_power",
            value=MATCH.epsilon_power
        ),
        OptionSelection(
            layer_index=MATCH.layer_index,
            layer_name="log_mel_spectrogram",
            question_key="log_mel_compression_mode",
            value=MATCH.compression_mode,
            status="resolved"
        ),
        TensorInfo(
            layer_index=MATCH.layer_index,
            layer_name="log_mel_spectrogram",
            tensor_name="sample_rate",
            role="shape_metadata",
            shape=MATCH.sample_rate
        ),
        TensorInfo(
            layer_index=MATCH.layer_index,
            layer_name="log_mel_spectrogram",
            tensor_name="output_num_frames",
            role="shape_metadata",
            shape=MATCH.num_frames
        ),
        TensorInfo(
            layer_index=MATCH.layer_index,
            layer_name="log_mel_spectrogram",
            tensor_name="output_mel_filters",
            role="shape_metadata",
            shape=MATCH.num_mel_filters
        ),
        TensorInfo(
            layer_index=MATCH.layer_index,
            layer_name="log_mel_spectrogram",
            tensor_name="output_channels",
            role="shape_metadata",
            shape=MATCH.channels
        ),
        WeightShape(
            layer_index=MATCH.layer_index,
            layer_name="log_mel_spectrogram",
            weight_name="log_mel_spectrogram_parameters",
            shape=MATCH.parameter_shape
        ),
        NOT(OutputStatus(
            layer_index=MATCH.layer_index,
            output_name="layer_result_printed",
            status="printed"
        )),
        salience=50
    )
    def print_log_mel_spectrogram_layer_result(
        self,
        layer_index,
        layer_title,
        input_shape,
        output_shape,
        epsilon_power,
        compression_mode,
        sample_rate,
        num_frames,
        num_mel_filters,
        channels,
        parameter_shape
    ):
        print_log_mel_spectrogram_result(
            layer_index=layer_index,
            layer_title=layer_title,
            layer_name="log_mel_spectrogram",
            layer_kind="speech_feature_extraction_layer",
            input_shape=input_shape,
            output_shape=output_shape,
            parameter_shape=parameter_shape,
            epsilon=f"1e-{int(epsilon_power)}",
            compression_mode=compression_mode,
            sample_rate=int(sample_rate),
            num_frames=int(num_frames),
            num_mel_filters=int(num_mel_filters),
            channels=int(channels)
        )

        self.declare(OutputStatus(
            layer_index=layer_index,
            output_name="layer_result_printed",
            status="printed"
        ))
