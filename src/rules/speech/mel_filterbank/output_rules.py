from experta import Rule, MATCH, NOT

from src.facts import (
    Layer,
    ComponentGroup,
    LayerParameter,
    TensorInfo,
    WeightShape,
    OutputStatus,
)
from src.utils.print_helpers import print_mel_filterbank_result


class MelFilterbankOutputRules:
    @Rule(
        Layer(
            layer_index=MATCH.layer_index,
            layer_name="mel_filterbank",
            layer_title=MATCH.layer_title,
            input_shape=MATCH.input_shape,
            output_shape=MATCH.output_shape
        ),
        ComponentGroup(
            group_index=MATCH.layer_index,
            group_name="mel_filterbank",
            internal_layers=MATCH.internal_layers,
            combine_operation=MATCH.combine_operation,
            status="computed"
        ),
        LayerParameter(
            layer_index=MATCH.layer_index,
            layer_name="mel_filterbank",
            parameter_name="num_mel_filters",
            value=MATCH.num_mel_filters
        ),
        LayerParameter(
            layer_index=MATCH.layer_index,
            layer_name="mel_filterbank",
            parameter_name="min_frequency_hz",
            value=MATCH.min_frequency_hz
        ),
        LayerParameter(
            layer_index=MATCH.layer_index,
            layer_name="mel_filterbank",
            parameter_name="max_frequency_hz",
            value=MATCH.max_frequency_hz
        ),
        TensorInfo(
            layer_index=MATCH.layer_index,
            layer_name="mel_filterbank",
            tensor_name="sample_rate",
            role="shape_metadata",
            shape=MATCH.sample_rate
        ),
        TensorInfo(
            layer_index=MATCH.layer_index,
            layer_name="mel_filterbank",
            tensor_name="nyquist_frequency_hz",
            role="shape_metadata",
            shape=MATCH.nyquist_frequency_hz
        ),
        TensorInfo(
            layer_index=MATCH.layer_index,
            layer_name="mel_filterbank",
            tensor_name="output_num_frames",
            role="shape_metadata",
            shape=MATCH.num_frames
        ),
        TensorInfo(
            layer_index=MATCH.layer_index,
            layer_name="mel_filterbank",
            tensor_name="input_frequency_bins",
            role="shape_metadata",
            shape=MATCH.frequency_bins
        ),
        TensorInfo(
            layer_index=MATCH.layer_index,
            layer_name="mel_filterbank",
            tensor_name="output_channels",
            role="shape_metadata",
            shape=MATCH.channels
        ),
        WeightShape(
            layer_index=MATCH.layer_index,
            layer_name="mel_filterbank",
            weight_name="mel_filterbank_parameters",
            shape=MATCH.parameter_shape
        ),
        NOT(OutputStatus(
            layer_index=MATCH.layer_index,
            output_name="layer_result_printed",
            status="printed"
        )),
        salience=50
    )
    def print_mel_filterbank_layer_result(
        self,
        layer_index,
        layer_title,
        input_shape,
        output_shape,
        internal_layers,
        combine_operation,
        num_mel_filters,
        min_frequency_hz,
        max_frequency_hz,
        sample_rate,
        nyquist_frequency_hz,
        num_frames,
        frequency_bins,
        channels,
        parameter_shape
    ):
        print_mel_filterbank_result(
            layer_index=layer_index,
            layer_title=layer_title,
            layer_name="mel_filterbank",
            layer_kind="speech_feature_extraction_component_group",
            input_shape=input_shape,
            output_shape=output_shape,
            parameter_shape=parameter_shape,
            internal_layers=internal_layers,
            combine_operation=combine_operation,
            sample_rate=int(sample_rate),
            nyquist_frequency_hz=int(nyquist_frequency_hz),
            num_mel_filters=int(num_mel_filters),
            min_frequency_hz=int(min_frequency_hz),
            max_frequency_hz=int(max_frequency_hz),
            num_frames=int(num_frames),
            frequency_bins=int(frequency_bins),
            channels=int(channels)
        )

        self.declare(OutputStatus(
            layer_index=layer_index,
            output_name="layer_result_printed",
            status="printed"
        ))
