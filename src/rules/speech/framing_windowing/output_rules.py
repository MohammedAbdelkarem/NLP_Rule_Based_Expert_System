from experta import Rule, MATCH, NOT

from src.facts import Layer, LayerParameter, OptionSelection, TensorInfo, WeightShape, OutputStatus
from src.utils.print_helpers import print_framing_windowing_result


class FramingWindowingOutputRules:
    @Rule(
        Layer(
            layer_index=MATCH.layer_index,
            layer_name="framing_windowing",
            layer_title=MATCH.layer_title,
            input_shape=MATCH.input_shape,
            output_shape=MATCH.output_shape
        ),
        LayerParameter(
            layer_index=MATCH.layer_index,
            layer_name="framing_windowing",
            parameter_name="frame_length_ms",
            value=MATCH.frame_length_ms
        ),
        LayerParameter(
            layer_index=MATCH.layer_index,
            layer_name="framing_windowing",
            parameter_name="hop_length_ms",
            value=MATCH.hop_length_ms
        ),
        OptionSelection(
            layer_index=MATCH.layer_index,
            layer_name="framing_windowing",
            question_key="window_function",
            value=MATCH.window_function,
            status="resolved"
        ),
        TensorInfo(
            layer_index=MATCH.layer_index,
            layer_name="framing_windowing",
            tensor_name="sample_rate",
            role="shape_metadata",
            shape=MATCH.sample_rate
        ),
        TensorInfo(
            layer_index=MATCH.layer_index,
            layer_name="framing_windowing",
            tensor_name="samples_per_channel",
            role="shape_metadata",
            shape=MATCH.samples_per_channel
        ),
        TensorInfo(
            layer_index=MATCH.layer_index,
            layer_name="framing_windowing",
            tensor_name="output_num_frames",
            role="shape_metadata",
            shape=MATCH.num_frames
        ),
        TensorInfo(
            layer_index=MATCH.layer_index,
            layer_name="framing_windowing",
            tensor_name="output_frame_length",
            role="shape_metadata",
            shape=MATCH.frame_length_samples
        ),
        TensorInfo(
            layer_index=MATCH.layer_index,
            layer_name="framing_windowing",
            tensor_name="output_channels",
            role="shape_metadata",
            shape=MATCH.channels
        ),
        WeightShape(
            layer_index=MATCH.layer_index,
            layer_name="framing_windowing",
            weight_name="framing_windowing_parameters",
            shape=MATCH.parameter_shape
        ),
        NOT(OutputStatus(
            layer_index=MATCH.layer_index,
            output_name="layer_result_printed",
            status="printed"
        )),
        salience=50
    )
    def print_framing_windowing_layer_result(
        self,
        layer_index,
        layer_title,
        input_shape,
        output_shape,
        frame_length_ms,
        hop_length_ms,
        window_function,
        sample_rate,
        samples_per_channel,
        num_frames,
        frame_length_samples,
        channels,
        parameter_shape
    ):
        hop_length_samples = (int(sample_rate) * hop_length_ms) // 1000

        print_framing_windowing_result(
            layer_index=layer_index,
            layer_title=layer_title,
            layer_name="framing_windowing",
            layer_kind="speech_preprocessing_layer",
            input_shape=input_shape,
            output_shape=output_shape,
            parameter_shape=parameter_shape,
            sample_rate=int(sample_rate),
            samples_per_channel=int(samples_per_channel),
            frame_length_ms=frame_length_ms,
            hop_length_ms=hop_length_ms,
            frame_length_samples=int(frame_length_samples),
            hop_length_samples=hop_length_samples,
            num_frames=int(num_frames),
            channels=int(channels),
            window_function=window_function
        )

        self.declare(OutputStatus(
            layer_index=layer_index,
            output_name="layer_result_printed",
            status="printed"
        ))
