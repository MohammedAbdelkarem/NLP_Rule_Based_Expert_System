from experta import MATCH, NOT, Rule

from src.facts import (
    ComponentGroup,
    IntermediateTensor,
    Layer,
    LayerParameter,
    OptionSelection,
    OutputStatus,
    WeightShape,
)
from src.utils.print_helpers import print_feedforward_classifier_head_result


class FeedforwardClassifierHeadOutputRules:
    @Rule(
        Layer(
            layer_index=MATCH.layer_index,
            layer_name="feedforward_classifier_head",
            layer_title=MATCH.layer_title,
            input_shape=MATCH.input_shape,
            output_shape=MATCH.output_shape,
        ),
        ComponentGroup(
            group_index=MATCH.layer_index,
            group_name="feedforward_classifier_head",
            internal_layers=MATCH.internal_layers,
            combine_operation=MATCH.combine_operation,
            status="computed",
        ),
        OptionSelection(
            layer_index=MATCH.layer_index,
            layer_name="feedforward_classifier_head",
            question_key="classifier_mode",
            value=MATCH.classifier_mode,
            status="resolved",
        ),
        LayerParameter(
            layer_index=MATCH.layer_index,
            layer_name="feedforward_classifier_head",
            parameter_name="hidden_dim",
            value=MATCH.hidden_dim,
        ),
        LayerParameter(
            layer_index=MATCH.layer_index,
            layer_name="feedforward_classifier_head",
            parameter_name="num_classes",
            value=MATCH.num_classes,
        ),
        WeightShape(
            layer_index=MATCH.layer_index,
            layer_name="feedforward_classifier_head",
            weight_name="feedforward_classifier_parameters",
            shape=MATCH.parameter_shape,
        ),
        IntermediateTensor(
            layer_index=MATCH.layer_index,
            layer_name="feedforward_classifier_head",
            tensor_name="hidden_projection_output",
            shape=MATCH.hidden_projection_shape,
        ),
        IntermediateTensor(
            layer_index=MATCH.layer_index,
            layer_name="feedforward_classifier_head",
            tensor_name="activation_output",
            shape=MATCH.activation_output_shape,
        ),
        IntermediateTensor(
            layer_index=MATCH.layer_index,
            layer_name="feedforward_classifier_head",
            tensor_name="logits_output",
            shape=MATCH.logits_shape,
        ),
        NOT(OutputStatus(
            layer_index=MATCH.layer_index,
            output_name="layer_result_printed",
            status="printed",
        )),
        salience=50,
    )
    def print_classifier_head_result(
        self,
        layer_index,
        layer_title,
        input_shape,
        output_shape,
        internal_layers,
        combine_operation,
        classifier_mode,
        hidden_dim,
        num_classes,
        parameter_shape,
        hidden_projection_shape,
        activation_output_shape,
        logits_shape,
    ):
        print_feedforward_classifier_head_result(
            layer_index=layer_index,
            layer_title=layer_title,
            layer_name="feedforward_classifier_head",
            layer_kind="classifier_head",
            input_shape=input_shape,
            output_shape=output_shape,
            internal_layers=internal_layers,
            combine_operation=combine_operation,
            classifier_mode=classifier_mode,
            hidden_dim=hidden_dim,
            num_classes=num_classes,
            parameter_shape=parameter_shape,
            hidden_projection_shape=hidden_projection_shape,
            activation_output_shape=activation_output_shape,
            logits_shape=logits_shape,
        )
        self.declare(OutputStatus(
            layer_index=layer_index,
            output_name="layer_result_printed",
            status="printed",
        ))
